await pagina.getByText('Base de datos', { exact: true }).last().click()
await foto('29-ajustes-base')
await pagina.keyboard.press('Escape')
await pagina.getByRole('button', { name: 'Generador' }).click()
await foto('30-generador')
await pagina.keyboard.press('Escape')
await pagina.getByRole('button', { name: 'Bloquear' }).click()
