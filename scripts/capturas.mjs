await pagina.locator('.pestanas--detalle .pestana').nth(3).click()
await foto('16-identidad-biografia')
await pagina.getByRole('button', { name: 'Editar' }).first().click()
await foto('17-editor-identidad-ficha')
await pagina.locator('.editor').evaluate((n) => n.closest('.columna')?.scrollTo(0, 99999))
