// Bucle de capturas de NARSIL Pass sobre la compilación de demostración (ui/dist-demo, puente en
// memoria). Recorre las pantallas como un operador y falla si hay errores de consola o de página.
//   node scripts/capturas.mjs [--ancho 1366 --alto 768] [--idioma es]
import { chromium } from '../ui/node_modules/playwright/index.mjs'
import { mkdirSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import path from 'node:path'

const raiz = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const arg = (n, d) => { const i = process.argv.indexOf(`--${n}`); return i > 0 ? process.argv[i + 1] : d }
const ancho = Number(arg('ancho', 1366)), alto = Number(arg('alto', 768))
const salida = path.join(raiz, 'capturas', `${ancho}x${alto}`)
mkdirSync(salida, { recursive: true })
const url = pathToFileURL(path.join(raiz, 'ui', 'dist-demo', 'index.html')).href

const navegador = await chromium.launch()
const pagina = await (await navegador.newContext({ viewport: { width: ancho, height: alto } })).newPage()
const errores = []
pagina.on('console', (m) => { if (m.type() === 'error') errores.push(m.text()) })
pagina.on('pageerror', (e) => errores.push(e.message))
const foto = async (n) => { await pagina.waitForTimeout(350); await pagina.screenshot({ path: path.join(salida, `${n}.png`) }); console.log('✓', n) }

await pagina.goto(url)
await pagina.getByRole('button', { name: 'Desbloquear' }).waitFor()
await foto('01-desbloqueo')
await pagina.locator('input[type=password]').fill('mala')
await pagina.keyboard.press('Enter')
await pagina.getByRole('alert').waitFor()
await foto('02-clave-erronea')
await pagina.locator('input[type=password]').fill('demo')
await pagina.keyboard.press('Enter')
await pagina.getByText('Intranet de la unidad').first().waitFor()
await foto('03-toda-la-base')
await pagina.locator('.lista').evaluate((n) => n.scrollTo(0, 99999))
await foto('03b-toda-la-base-final')
await pagina.locator('.vista').filter({ hasText: 'Servicios internos' }).click()
await pagina.getByText('Intranet de la unidad').first().click()
await foto('04-entrada-repetida')
await pagina.getByText('Infraestructura').first().click()
await pagina.getByText('VPN corporativa').first().click()
await foto('05-entrada-adjunto')
await pagina.getByText('VPN corporativa').first().click({ button: 'right' })
await foto('06-menu-contextual')
await pagina.keyboard.press('Escape')
await pagina.getByRole('button', { name: 'Editar' }).first().click()
await foto('07-editor')
await pagina.locator('.editor input').first().fill('VPN corporativa (cambio)')
await pagina.keyboard.press('Escape')
await pagina.getByText('Descartar cambios').waitFor()
await foto('08-descartar-cambios')
await pagina.getByRole('button', { name: 'Descartar' }).click()
await pagina.locator('.vista').filter({ hasText: 'Servicios externos' }).click()
await pagina.getByText('Correo de la operación').first().click()
await foto('09-externos-totp')
await pagina.getByRole('button', { name: 'Filtros' }).click()
await pagina.locator('.filtros select').nth(2).selectOption('cualquiera')
await foto('10-filtro-avisos')
await pagina.getByText('Quitar filtros').click()
await pagina.getByRole('button', { name: 'Filtros' }).click()
await pagina.locator('.vista').filter({ hasText: 'Identidades operativas' }).click()
await pagina.getByText('Marta Ribas').first().click()
await pagina.waitForTimeout(300)
await foto('11-identidad-ficha')
await pagina.locator('.pestanas--detalle .pestana').nth(1).click()
await foto('12-identidad-servicios')
await pagina.locator('.pestanas--detalle .pestana').nth(2).click()
await foto('13-identidad-fotos')
await pagina.locator('.miniatura').first().click()
await foto('14-visor')
