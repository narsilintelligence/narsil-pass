await pagina.locator('.editor .pestanas--detalle .pestana').nth(1).click()
await pagina.locator('.editor').evaluate((n) => n.closest('.columna')?.scrollTo(0, 0))
await foto('19-editor-identidad-servicios')
await pagina.locator('.editor .pestanas--detalle .pestana').nth(3).click()
await foto('20-editor-identidad-cuenta')
await pagina.getByRole('button', { name: 'Cancelar' }).click()
await pagina.getByRole('button', { name: 'Nueva identidad operativa' }).first().click()
await pagina.locator('.menu').getByText('Nueva identidad operativa').click()
await foto('21-nueva-identidad')
await pagina.getByRole('button', { name: 'Cancelar' }).click()
await pagina.getByRole('button', { name: 'Salud' }).click()
await foto('22-salud-repetidas')
await pagina.locator('.dialogo .pestana').nth(2).click()
